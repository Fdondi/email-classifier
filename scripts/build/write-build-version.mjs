import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const versionPath = join(root, 'docs', 'VERSION.md');
const line = readFileSync(versionPath, 'utf8').split(/\r?\n/, 1)[0] ?? '';
const match = line.match(/^(\d+\.\d+\.\d+)\b/);
if (!match) {
  console.error(`Could not parse version from first line of ${versionPath}: ${JSON.stringify(line)}`);
  process.exit(1);
}
const version = match[1];

const args = new Set(process.argv.slice(2));
const writeFrontend = !args.has('--backend-only');
const writeBackend = !args.has('--frontend-only');

function writeIfChanged(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  let previous = null;
  try {
    previous = readFileSync(path, 'utf8');
  } catch {
    previous = null;
  }
  if (previous === contents) {
    return false;
  }
  writeFileSync(path, contents);
  return true;
}

const written = [];

if (writeFrontend) {
  const frontendPath = join(root, 'frontend', 'src', 'app', 'build-version.ts');
  if (writeIfChanged(frontendPath, `/** Generated by scripts/build/write-build-version.mjs — do not edit. */\nexport const BUILD_VERSION = '${version}';\n`)) {
    written.push(frontendPath);
  }
}

if (writeBackend) {
  const backendPath = join(root, 'backend', 'src', 'main', 'resources', 'build-version.properties');
  if (writeIfChanged(backendPath, `# Generated by scripts/build/write-build-version.mjs — do not edit.\nversion=${version}\n`)) {
    written.push(backendPath);
  }
}

console.log(`Build version ${version}${written.length ? ` → ${written.map((p) => p.slice(root.length + 1)).join(', ')}` : ' (unchanged)'}`);
